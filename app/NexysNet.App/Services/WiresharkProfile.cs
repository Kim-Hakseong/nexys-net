using System.Globalization;
using System.IO;
using System.Text;
using NexysView.Core.Mil1553;

namespace NexysNet.App.Services;

/// <summary>
/// Writes a Wireshark configuration for the project's ARINC 664 ICD — written from scratch by NexysNet, no Wireshark file is copied:
/// <list type="bullet">
/// <item><c>plugins/nexysnet_afdx.lua</c>: a post-dissector that adds VL, VL name, sequence number and network A/B to every frame sent to
/// 03:00:00:00:vv:vv, and a dissector registered on every ICD UDP destination port that decodes the parameters (EU = raw × scale + offset)
/// — after Wireshark's own IP reassembly for fragmented queuing-port messages.</item>
/// <item><c>profiles/NexysNet-AFDX/preferences</c>: columns Net · VL · VL name · SN next to the usual ones.</item>
/// <item><c>profiles/NexysNet-AFDX/colorfilters</c>: network A / B colours, sequence-number field present.</item>
/// </list>
/// The folder has the layout of a Wireshark personal configuration folder: copy <c>plugins</c> and <c>profiles</c> into it
/// (Help › About Wireshark › Folders), or point the WIRESHARK_CONFIG_DIR environment variable at it.
/// </summary>
public static class WiresharkProfile
{
    public const string ProfileName = "NexysNet-AFDX";

    public static string Write(string dir, IcdHub icd, string tool)
    {
        var ic = CultureInfo.InvariantCulture; var vls = icd.Vls ?? new();
        string plug = Path.Combine(dir, "plugins"), prof = Path.Combine(dir, "profiles", ProfileName);
        Directory.CreateDirectory(plug); Directory.CreateDirectory(prof);
        var l = new StringBuilder();
        l.Append($"-- ARINC 664 (AFDX) decoding generated by {tool} on {DateTime.Now:yyyy-MM-dd HH:mm} from ICD '{Esc(icd.Source ?? "")}' ({vls.Count} VLs).\n");
        l.Append("-- Load: copy into the Wireshark personal plugins folder, or: tshark -X lua_script:nexysnet_afdx.lua -r capture.pcapng\n");
        l.Append("local p = Proto(\"nexysafdx\", \"NexysNet ARINC 664 VL\")\n");
        l.Append("local f_vl = ProtoField.uint16(\"nexysafdx.vl\", \"VL\")\nlocal f_name = ProtoField.string(\"nexysafdx.vl_name\", \"VL name\")\nlocal f_sn = ProtoField.uint8(\"nexysafdx.sn\", \"Sequence number\")\nlocal f_net = ProtoField.string(\"nexysafdx.net\", \"Network\")\nlocal f_bag = ProtoField.double(\"nexysafdx.bag_ms\", \"BAG (ms)\")\n");
        l.Append("p.fields = { f_vl, f_name, f_sn, f_net, f_bag }\n");
        l.Append("local vlinfo = {\n"); foreach (var v in vls) l.Append(FormattableString.Invariant($"  [{v.VlId}] = {{ name = \"{Esc(v.Name)}\", bag = {v.BagMs} }},\n")); l.Append("}\n");
        l.Append(@"local f_ipoff = Field.new(""ip.frag_offset"")
local f_iplen = Field.new(""ip.len"")
function p.dissector(tvb, pinfo, tree)
  local n = tvb:len()
  if n < 35 or tvb(0, 4):uint() ~= 0x03000000 then return end
  local vl = tvb(4, 2):uint()
  local t = tree:add(p, tvb(), ""ARINC 664 VL "" .. vl)
  t:add(f_vl, tvb(4, 2))
  local info = vlinfo[vl]
  if info then t:add(f_name, info.name); t:add(f_bag, info.bag) end
  local iplen = f_iplen()
  local snat = n - 1
  if iplen and 14 + iplen.value < n then snat = 14 + iplen.value end
  t:add(f_sn, tvb(snat, 1))
  local id = bit.rshift(tvb(11, 1):uint(), 5)
  if tvb(6, 1):uint() == 2 and (id == 1 or id == 2) then t:add(f_net, id == 1 and ""A"" or ""B"") end
end
register_postdissector(p)
");
        l.Append("local q = Proto(\"nexysafdxport\", \"NexysNet ARINC 664 port\")\nlocal pf = {}\nlocal ports = {}\n");
        int k = 0; var fieldNames = new List<string>();
        foreach (var v in vls) foreach (var port in v.Ports)
        {
            if (port.UdpDst <= 0) continue;
            l.Append(FormattableString.Invariant($"ports[{port.UdpDst}] = {{ vl = {v.VlId}, name = \"{Esc(port.Name)}\", items = {{\n"));
            foreach (var prm in port.Params)
            {
                string fn = $"nexysafdx.p{k++}"; fieldNames.Add($"pf[\"{fn}\"]");
                l.Append(FormattableString.Invariant($"  {{ f = \"{fn}\", name = \"{Esc(prm.Name)}\", off = {prm.Offset}, size = {prm.Size}, t = \"{prm.Type}\", be = {(prm.Endian == "little" ? "false" : "true")}, scale = {prm.Scale.ToString("R", ic)}, ofs = {prm.OffsetVal.ToString("R", ic)}, unit = \"{Esc(prm.Unit)}\" }},\n"));
            }
            l.Append("} }\n");
        }
        l.Append(@"for _, d in pairs(ports) do for _, it in ipairs(d.items) do
  pf[it.f] = ProtoField.double(it.f, it.name .. (it.unit ~= """" and ("" ("" .. it.unit .. "")"") or """"))
end end
local fl = {} for _, f in pairs(pf) do fl[#fl + 1] = f end
q.fields = fl
local function raw(r, it)
  local s = it.t:sub(1, 1)
  if s == ""f"" then return it.be and r:float() or r:le_float() end
  if it.size == 8 then
    local v = s == ""i"" and (it.be and r:int64() or r:le_int64()) or (it.be and r:uint64() or r:le_uint64())
    return tonumber(tostring(v))
  end
  if s == ""i"" then return it.be and r:int() or r:le_int() end
  return it.be and r:uint() or r:le_uint()
end
function q.dissector(tvb, pinfo, tree)
  local d = ports[pinfo.dst_port]
  if not d then return 0 end
  local t = tree:add(q, tvb(), ""VL "" .. d.vl .. "" port "" .. d.name)
  for _, it in ipairs(d.items) do
    if it.off + it.size <= tvb:len() then
      local r = tvb(it.off, it.size)
      t:add(pf[it.f], r, raw(r, it) * it.scale + it.ofs)
    end
  end
  pinfo.cols.protocol:set(""AFDX"")
  return tvb:len()
end
local udp = DissectorTable.get(""udp.port"")
for port, _ in pairs(ports) do udp:add(port, q) end
");
        File.WriteAllText(Path.Combine(plug, "nexysnet_afdx.lua"), l.ToString(), new UTF8Encoding(false));
        // profile: columns
        var cols = new[] { ("No.", "%m"), ("Time", "%t"), ("Net", "%Cus:nexysafdx.net:0:R"), ("VL", "%Cus:nexysafdx.vl:0:R"), ("VL name", "%Cus:nexysafdx.vl_name:0:R"), ("SN", "%Cus:nexysafdx.sn:0:R"), ("Source", "%s"), ("Destination", "%d"), ("Protocol", "%p"), ("Length", "%L"), ("Info", "%i") };
        File.WriteAllText(Path.Combine(prof, "preferences"), $"# Wireshark profile {ProfileName} written by {tool}\ngui.column.format:\n" + string.Join(",\n", cols.Select(c => $"\t\"{c.Item1}\", \"{c.Item2}\"")) + "\n", new UTF8Encoding(false));
        // colour rules: @name@filter@[bg r,g,b][fg r,g,b] (16-bit components)
        File.WriteAllText(Path.Combine(prof, "colorfilters"),
            "# Wireshark colouring rules written by " + tool + "\n" +
            "@AFDX network A@nexysafdx.net == \"A\"@[56540,61423,65535][0,0,0]\n" +
            "@AFDX network B@nexysafdx.net == \"B\"@[65535,59367,52428][0,0,0]\n" +
            "@AFDX VL (no interface id)@nexysafdx.vl && !nexysafdx.net@[61166,61166,61166][0,0,0]\n" +
            "@ARP@arp@[64250,61680,55255][4626,4626,4626]\n", new UTF8Encoding(false));
        File.WriteAllText(Path.Combine(dir, "README.txt"),
            $"Wireshark configuration for ARINC 664, written by {tool}.\n\n" +
            "plugins\\nexysnet_afdx.lua  - VL / VL name / SN / network fields and ICD parameter decoding (UDP destination ports of the ICD)\n" +
            $"profiles\\{ProfileName}\\        - columns (Net, VL, VL name, SN) and colour rules (A / B)\n\n" +
            "Use: copy 'plugins' and 'profiles' into the Wireshark personal configuration folder (Help > About Wireshark > Folders),\n" +
            $"restart Wireshark and choose the profile '{ProfileName}' (Edit > Configuration Profiles).\n" +
            "Or for one session: set WIRESHARK_CONFIG_DIR to this folder before starting Wireshark / tshark.\n" +
            "Display filters: nexysafdx.vl == 10, nexysafdx.net == \"B\", nexysafdx.sn == 0, nexysafdxport.\n", new UTF8Encoding(false));
        return dir;
    }
    static string Esc(string s) => s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", " ");
}
